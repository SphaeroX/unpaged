#!/usr/bin/env bash
# Writes tests/screenshots/sample_pdfs.g.dart: the corpus PDFs used for the
# README screenshots as Base64 constants (inlined so no test asset ends up in
# the app bundle). Run from the project root after changing the sample PDFs:
#   bash tests/screenshots/tool/generate_sample_pdfs.sh
set -euo pipefail

corpus=tests/reflow_engine/corpus
out=tests/screenshots/sample_pdfs.g.dart

constant() { # <name> <file> <doc comment>
  printf '/// %s\n' "$3"
  printf 'const %s =\n    %s%s%s;\n\n' "$1" "'" "$(base64 -w0 "$corpus/$2")" "'"
}

{
  echo '// GENERATED by tests/screenshots/tool/generate_sample_pdfs.sh – do not edit.'
  echo '// Sources and licences: tests/reflow_engine/corpus/SOURCES.md'
  echo
  constant paperPdf two_column_figures.pdf \
    'two_column_figures.pdf (arXiv:2611.19296, CC BY 4.0, pages 1–3).'
  constant singleColumnPdf synthetic_single_column.pdf \
    'synthetic_single_column.pdf (CC0).'
  constant twoColumnPdf synthetic_two_column.pdf \
    'synthetic_two_column.pdf (CC0).'
} > "$out"
dart format "$out" > /dev/null
echo "wrote $out"
